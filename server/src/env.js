/* Чтение переменных окружения.

   Пустое значение — это «не задано», а не «пустая строка». Разница
   не теоретическая: `.env.example` задуман как образец, его копируют
   в `.env` и заполняют не все строки сразу. Обычная запись
   `Number(process.env.PORT ?? 3000)` в этом случае даёт не 3000, а ноль:
   `??` подставляет умолчание только вместо undefined и null, а из файла
   приходит пустая строка. Сервер послушно занимал случайный порт и
   печатал «слушает http://127.0.0.1:0».

   Хуже того же самого в порогах ограничения частоты: пустая строка
   превращалась в ноль, а ноль по нашему же соглашению означает
   «ограничение выключено». Копирование образца молча снимало защиту
   от перебора паролей. */

/** Строка из окружения; пустая и состоящая из пробелов считается незаданной. */
export function text(name, fallback = null) {
  const raw = process.env[name];
  if (raw === undefined || raw.trim() === '') return fallback;
  return raw.trim();
}

/** Целое из окружения. Незаданное, нечисловое или отрицательное — умолчание. */
export function number(name, fallback, { min = 0 } = {}) {
  const raw = text(name);
  if (raw === null) return fallback;

  const value = Number(raw);
  if (!Number.isFinite(value) || value < min) {
    console.warn(`[окружение] ${name}=${raw} — не годится, беру значение по умолчанию ${fallback}`);
    return fallback;
  }
  return value;
}

/** Признак: включённым считается только явное «true». */
export const flag = (name) => text(name) === 'true';
