-- Уведомления внутри кабинета.
--
-- Таблица notifications, заведённая в 001 и пересобранная в 005, — это очередь
-- отправки наружу: у строки есть канал (telegram, sms, почта, пуш), время
-- отправки, отметка «отправлено» и текст ошибки. Её разбирает отправщик,
-- а человек её не видит и прочитанной пометить не может.
--
-- Здесь нужно другое: список сообщений, который клиентка открывает в кабинете
-- и просматривает. У него нет канала и нет доставки — он и есть экран. Отметка
-- о прочтении принадлежит человеку, а не отправщику. Поэтому отдельная таблица,
-- а не ещё один channel в очереди: канал 'cabinet' потянул бы за собой
-- бессмысленные для экрана поля scheduled_at, sent_at и error, а признак
-- прочтения пришлось бы прятать в status.

CREATE TABLE inbox (
  id             INTEGER PRIMARY KEY,
  user_id        INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,

  -- Повод. Список закрытый: уведомление создаётся только о том, что человек
  -- сделал не сам. Собственная запись, отмена и перенос сюда не попадают —
  -- он их только что выполнил и результат уже видел.
  kind           TEXT    NOT NULL CHECK (kind IN (
                           'appointment_cancelled',  -- визит отменила студия
                           'appointment_moved',      -- визит перенесла студия
                           'slot_overlapped')),      -- на то же время назначили ещё один визит

  -- Готовый текст, а не шаблон с подстановкой при показе. Сообщение описывает
  -- то, что было в момент события: если запись потом перенесут ещё раз,
  -- старое уведомление должно остаться правдой о прошлом переносе.
  text           TEXT    NOT NULL,

  -- Куда ведёт ссылка. NULL остаётся, если запись потом удалят: сообщение
  -- переживает свой повод, но перестаёт быть ссылкой.
  appointment_id INTEGER REFERENCES appointments (id) ON DELETE SET NULL,

  read_at        TEXT,
  created_at     TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
);

-- Список кабинета: свои сообщения, новые сверху.
CREATE INDEX inbox_user_idx ON inbox (user_id, created_at DESC);

-- Счётчик непрочитанного в шапке. Частичный индекс: прочитанные строки
-- в него не попадают, а спрашивают всегда именно непрочитанные.
CREATE INDEX inbox_unread_idx ON inbox (user_id) WHERE read_at IS NULL;
