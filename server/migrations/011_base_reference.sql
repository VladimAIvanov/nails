-- Справочники, без которых студия не может начать работу на чистом сервере.
--
-- Обнаружено при первом развёртывании: на пустой базе администратор не мог
-- завести ни одной услуги. POST /api/admin/services требует category_id
-- и проверяет, что такая категория есть, а категории до сих пор появлялись
-- только из сидов — то есть вместе с десятью демо-услугами, тремя мастерами
-- и общим паролем, напечатанным в README. На опубликованном сервисе это
-- не годится, а без категорий панель студии оказывалась бесполезной.
--
-- Здесь только справочные строки: рубрики прайса и блоки первого экрана.
-- Ни услуг, ни мастеров, ни записей, ни учётных записей — их заводит студия
-- сама, из своей панели. Это тот же род данных, что в 002_reference.sql:
-- настройки студии, часы работы и названия статусов.
--
-- Тексты блоков заведомо нейтральные: они существуют, чтобы их было чем
-- заменить. PATCH /api/admin/content/:slug умеет только менять существующий
-- блок и не умеет создавать новый, поэтому пустая таблица означала бы,
-- что первый экран не отредактировать никогда.

