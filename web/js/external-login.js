/* Кнопка «Войти с Яндекс ID» на экранах входа и регистрации.

   Кнопка появляется, только если внешний вход настроен: список доступных
   способов приходит в `GET /api/studio` полем `external_login`. Пустой
   список — кнопки нет. Рисовать кнопку, которая всегда отвечает отказом,
   хуже, чем не рисовать её вовсе.

   Почту страница не отправляет и отправить не может: сервер её не принимает.
   Кто пришёл, решает он сам — по одноразовому коду, который Яндекс кладёт
   в адрес возврата.

   Это ссылка, а не кнопка с обработчиком, и так задумано. Вход через Яндекс —
   это уход со страницы на чужой сайт, а не запрос из скрипта: браузер должен
   выполнить обычный переход, чтобы потом вернуться сюда с кодом. */
import { el, studio } from './api.js';

/**
 * Дорисовывает кнопку в элемент с заданным id, если внешний вход доступен.
 * @param {string} mountId куда вставить
 * @param {string|null} next адрес возврата после входа
 */
export async function renderExternalLogin(mountId, next = null) {
  const mount = document.getElementById(mountId);
  if (!mount) return;

  let providers = [];
  try {
    providers = (await studio()).external_login ?? [];
  } catch {
    /* Настройки не приехали — экран входа с паролем всё равно работает,
       и загораживать его сообщением об ошибке из-за кнопки незачем. */
    return;
  }

  if (!providers.includes('yandex')) return;

  /* Адрес возврата после входа передаём серверу: он положит его в куку
     и вспомнит, когда человек вернётся от Яндекса. Через сам Яндекс его
     проносить нельзя — то, что уходит наружу, возвращается изменённым. */
  const href = next
    ? `/api/auth/yandex/start?next=${encodeURIComponent(next)}`
    : '/api/auth/yandex/start';

  const link = el('a', { className: 'ya-btn', href, rel: 'nofollow' },
    /* Знак — украшение: читающему с экрана он сообщил бы лишнюю букву,
       поэтому спрятан от него. Свойство ariaHidden, а не атрибут: el()
       присваивает свойства, и имя с дефисом до разметки не доехало бы. */
    el('span', { className: 'ya-btn__mark', textContent: 'Я', ariaHidden: 'true' }),
    el('span', { textContent: 'Войти с Яндекс ID' })
  );

  mount.replaceChildren(
    el('div', { className: 'or' }, el('span', { textContent: 'или' })),
    link
  );
}
